"""Cross-provider evaluation on the bundled samples.

    GOOGLE_CLOUD_PROJECT=<proj> .venv/bin/python evals/run.py --providers mock,vertex,openai

Invariant (must hold on every run): the recommended configuration and its cost equal the model-free run.
Reported: notes kept/rejected, model proposals listed/rejected, cost and latency of the model calls."""

import argparse
import asyncio
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
for line in (ROOT / ".env").read_text().splitlines() if (ROOT / ".env").exists() else []:
    k, _, v = line.partition("=")
    if k and not k.startswith("#") and k != "RIGHTSIZE_LLM":
        os.environ.setdefault(k, v)

from rightsize.llm import Budget, make_llm  # noqa: E402
from rightsize.models import Snapshot  # noqa: E402
from rightsize.orchestrator import recommend  # noqa: E402

SAMPLES = ROOT / "rightsize" / "samples"


async def main(providers, out):
    rows = []
    for p in sorted(SAMPLES.glob("*.json")):
        snap = Snapshot.model_validate_json(p.read_text())
        base = await recommend(snap, make_llm("none"))
        rows.append((p.stem, "none/none", base, True))
        print(p.stem, "none", base.best.monthly_usd, flush=True)
        for prov in providers:
            r = await recommend(snap, make_llm(prov), budget=Budget())
            same = r.best.config == base.best.config and r.best.monthly_usd == base.best.monthly_usd
            rows.append((p.stem, f"{r.provider}/{r.model}", r, same))
            print(p.stem, prov, same, flush=True)
    bad = sum(not ok for *_, ok in rows)
    L = [
        "# Evaluation results",
        "",
        "Generated by `evals/run.py`. The recommended configuration must equal the model-free result on every run.",
        "",
        "| sample | provider | current $/mo | recommended $/mo | saving | feasible now -> after | stable | note kept | proposals listed / rejected | model cost |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, prov, r, ok in rows:
        prop_ok = sum("model-proposed" in " ".join(a.violations) for a in r.alternatives)
        prop_bad = sum(d["agent"] == "proposer" for d in r.dropped)
        cost = sum(s.cost_usd for s in r.trace)
        L.append(
            f"| {name} | {prov} | {r.current.monthly_usd:.2f} | {r.best.monthly_usd:.2f} | {r.saving_pct:.0f}% | "
            f"{'yes' if r.current.feasible else 'no'} -> {'yes' if r.best.feasible else 'no'} | {'✓' if ok else '✗'} | "
            f"{'✓' if r.note else ('rejected' if any(d['agent'] == 'explainer' for d in r.dropped) else '-')} | {prop_ok} / {prop_bad} | ${cost:.4f} |"
        )
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out}; invariant violations: {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--providers", default="mock")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "eval-results.md")
    a = ap.parse_args()
    sys.exit(asyncio.run(main(a.providers.split(","), a.out)))
