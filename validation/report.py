"""Write docs/validation-results.md from validation/comparison-*.json."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def pct(m, p):
    return "n/a" if not m else f"{(p - m) / m:+.0%}"


def table(name, d, role):
    m, p, r = d["measured"], d["predicted"], d["run"]
    rows = [
        ("Requests", m["requests"], p["requests"], "count"),
        ("Instances started", m["instances_started"], p["instances_started"], "count"),
        ("Peak instances", m["peak_instances"], p["peak_instances"], "count"),
        (
            "Server-side p50 latency (ms)",
            round(m["p50_ms"]),
            round(p["p50_ms"]),
            "warm service time",
        ),
        (
            "Client p95 latency (ms)",
            round(r["client_p95_ms"]),
            round(p["p95_ms"]),
            "includes cold-start waits",
        ),
        (
            "Client p99 latency (ms)",
            round(r["client_p99_ms"]),
            round(p["p99_ms"]),
            "includes cold-start waits",
        ),
        (
            "Billable instance-seconds",
            round(m["billable_s"]),
            round(p["billable_s"]),
            "request-based billing",
        ),
    ]
    out = [
        f"## Pattern {name} ({role})",
        "",
        f"Bursts (start s, requests, length s): {r['bursts']}; each request waits {r['work_ms']} ms; {r['sent']} sent, {r['ok']} succeeded, {r['errors']} failed.",
        f"Measured startup latency quantiles p5/p50/p95/p99 (s): {m.get('startup_quantiles_s')}.",
        "",
        "| metric | measured | predicted | error | note |",
        "|---|---|---|---|---|",
    ]
    out += [f"| {a} | {b} | {c} | {pct(b, c)} | {n} |" for a, b, c, n in rows]
    return out


def main():
    parts = [
        "# Simulator validation against a real Cloud Run service",
        "",
        "A service with known settings (1 vCPU, 512 MiB, concurrency 4, min 0, max 10, request-based billing; `rs-target`) was driven with scripted bursts "
        "after scaling to zero. Cloud Monitoring's measurements for the window are compared with the simulator's prediction for the same arrival schedule "
        "and settings, using the service's own measured latency and startup-latency quantiles as inputs (no fitting to the outcome). "
        "Generated by `validation/report.py`; raw numbers in `validation/comparison-*.json`.",
        "",
    ]
    for name, role in (
        ("A", "used to choose the model's routing, scale-out and billing assumptions"),
        ("B", "also seen while choosing them"),
        ("C", "run after the model was frozen: the only true holdout"),
    ):
        f = ROOT / "validation" / f"comparison-{name}.json"
        if f.exists():
            parts += table(name, json.loads(f.read_text()), role) + [""]
    (ROOT / "docs" / "validation-results.md").write_text("\n".join(parts) + "\n")
    print("wrote docs/validation-results.md")


if __name__ == "__main__":
    main()
